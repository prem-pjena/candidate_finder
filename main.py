@app.get("/", response_model=HealthResponse)
async def health_check():
    """
    Simple health check — confirms the API is running and data is loaded.
    
    Returns:
        {"status": "ok", "candidates_loaded": 500}
    """
    return HealthResponse(
        status="ok",
        candidates_loaded=len(candidates),
    )


@app.post("/search", response_model=SearchResponse)
async def search_candidates(request: SearchRequest):
    """
    The main search endpoint — find candidates matching a hiring requirement.
    
    This is the endpoint recruiters will actually use. They send a plain-language
    requirement, and we return the top 20 candidates with scores and reasons.
    
    Example request body:
        {"requirement": "Customer Success Manager, 3+ years, fintech background, Bangalore"}
    
    Example response:
        {
            "query": "Customer Success Manager, 3+ years, fintech background, Bangalore",
            "total_results": 20,
            "broaden_used": false,
            "results": [
                {"rank": 1, "name": "Priya Sharma", "title": "Customer Success Manager",
                 "score": 92, "reason": "CSM title matches, 5yr exp, fintech, Bangalore"}
            ]
        }
    
    I handle errors at three levels:
    1. No candidates loaded → 503 (data issue)
    2. LLM unavailable → 503 (infrastructure issue)
    3. Unexpected errors → 500 (bug)
    """
    # ── Pre-flight checks ──────────────────────────────────────────────
    if not candidates:
        raise HTTPException(
            status_code=503,
            detail="No candidates loaded. Check that candidates.json exists and is valid.",
        )

    requirement_text = request.requirement.strip()
    if not requirement_text:
        raise HTTPException(
            status_code=400,
            detail="Requirement text cannot be empty.",
        )

    # ── Run the pipeline ───────────────────────────────────────────────
    try:
        results, broaden_used = _search_pipeline(
            requirement_text,
            enable_broaden=request.broaden,
        )

        return SearchResponse(
            query=requirement_text,
            total_results=len(results),
            broaden_used=broaden_used,
            results=results,
        )

    except ConnectionError as e:
        # This happens when LM Studio isn't running
        raise HTTPException(
            status_code=503,
            detail=f"LLM service unavailable: {e}",
        )
    except RuntimeError as e:
        # Something went wrong during LLM parsing or scoring
        raise HTTPException(
            status_code=500,
            detail=f"Search failed: {e}",
        )
    except Exception as e:
        # Catch-all for unexpected errors (so the API returns JSON, not a crash)
        logger.exception("Unexpected error during search")
        raise HTTPException(
            status_code=500,
            detail=f"Unexpected error: {e}",
        )
